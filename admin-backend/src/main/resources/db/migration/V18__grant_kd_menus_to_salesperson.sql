-- V18：把金蝶同步相关菜单授予「普通用户」角色（业务员）
--
-- 背景：金蝶对账（M1~M4）的目标用户就是业务员本人——桌面采集器同步自己账套的
-- 出库数据，业务员登录网页端查看并「导出对账单」（docs/金蝶对账同步方案.md §1）。
-- V16/V17 建菜单时只授权给超级管理员(1)与普通管理员(2)，业务员账号登录后：
--   1. 侧边栏没有「金蝶同步 → 对账单」，页面不可达；
--   2. 直接调用 /kd/statement/summary | /export 一律 403。
-- 即功能对管理员可用、对真正的使用者（业务员）完全不可用。
--
-- 本迁移把业务员自助闭环所需的菜单授予 role_id=3（普通用户，种子账号 test）：
--   - 绑定管理：生成绑定码 / 吊销自己机器的令牌（换电脑）/ 下发「立即同步」；
--   - 同步批次：只看本人批次（后端已按 ownerUserId 过滤），便于自查数据为何没上来；
--   - 对账单：查询 + 导出（本功能核心）。
-- 不授予：同步配置(43/4301~4304)——改字段映射与任务清单属运维操作。
-- 相关接口（绑定列表 / 指令 / 吊销 / 批次）服务层均已做本人隔离，业务员互不可见。
--
-- 同时把 role 3 的数据权限对齐方案 §1 的「仅本人」（data_scope = 4，
-- 该档位 DataScopePolicy 已实现；role 3 无系统用户管理菜单，不受切面影响）。
--
-- 上线提示：生产环境若为业务员另建了角色，需在「角色管理」里勾选同样的
-- 菜单集合（金蝶同步目录 + 绑定管理 + 同步批次 + 对账单及其按钮）。
-- =============================================================================


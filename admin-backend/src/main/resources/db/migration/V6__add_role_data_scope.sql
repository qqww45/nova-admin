-- V6：角色增加「数据权限范围」字段
--
-- 范围含义（与领域枚举 DataScope 一一对应）：
--   1 = 全部数据（不受限）
--   2 = 本部门
--   3 = 本部门及下级（暂未在切面实现，枚举已预留扩展点）
--   4 = 仅本人（暂未在切面实现，枚举已预留扩展点）
--   5 = 自定义部门（暂未在切面实现，需要 sys_role_dept 配套表，未创建）
--
-- 默认值：超级管理员 → 1（全部）；普通管理员 → 2（本部门）
-- 这两个角色之外的现有角色会保持默认 1。
-- =============================================================================

ALTER TABLE sys_role ADD COLUMN data_scope INTEGER DEFAULT 1;

UPDATE sys_role SET data_scope = 1 WHERE id = 1;
UPDATE sys_role SET data_scope = 2 WHERE id = 2;

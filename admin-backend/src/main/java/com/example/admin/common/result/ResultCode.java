package com.example.admin.common.result;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 统一错误码枚举。
 *
 * <p>约定：
 * <ul>
 *     <li>200 成功；</li>
 *     <li>401 未认证 / 令牌失效；403 无权限；500 服务器内部错误；</li>
 *     <li>1000+ 为业务错误码，前端可据此做差异化提示或国际化。</li>
 * </ul>
 *
 * @author admin-system
 * @since 2026-01-01
 */
@Getter
@AllArgsConstructor
public enum ResultCode {

    /** 操作成功 */
    SUCCESS(200, "操作成功"),

    /** 请求参数错误 */
    BAD_REQUEST(400, "请求参数错误"),

    /** 未认证或令牌失效（前端收到后跳转登录页） */
    UNAUTHORIZED(401, "认证失败，请重新登录"),

    /** 无访问权限 */
    FORBIDDEN(403, "没有权限访问该资源"),

    /** 资源不存在 */
    NOT_FOUND(404, "资源不存在"),

    /** 服务器内部错误 */
    ERROR(500, "服务器内部错误，请联系管理员"),

    // ---------------- 业务错误码（1000+） ----------------
    /** 通用业务异常 */
    BIZ_ERROR(1000, "业务处理失败"),

    /** 参数校验失败 */
    PARAM_ERROR(1001, "参数校验失败"),

    /** 账号已停用 */
    USER_DISABLED(1002, "账号已停用，请联系管理员"),

    /** 账号因连续登录失败被临时锁定 */
    LOGIN_LOCKED(1003, "登录失败次数过多，账号已锁定，请稍后再试"),

    /** 验证码过期 */
    CAPTCHA_EXPIRED(1004, "验证码已过期，请点击刷新"),

    /** 验证码不正确 */
    CAPTCHA_ERROR(1005, "验证码不正确"),

    /** 用户名或密码错误（不区分“用户不存在/密码错误”，避免账号枚举） */
    USERNAME_OR_PASSWORD_ERROR(1006, "用户名或密码错误"),

    /** 令牌无效或已过期 */
    TOKEN_INVALID(1007, "令牌无效或已过期"),

    /** 重复提交 */
    REPEAT_SUBMIT(1008, "请勿重复提交"),

    /** 数据不存在 */
    DATA_NOT_FOUND(1009, "数据不存在或已被删除"),

    /** 数据已存在（唯一性冲突） */
    DATA_EXIST(1010, "数据已存在，请勿重复添加"),

    /** 请求过于频繁（限流） */
    REQUEST_TOO_FREQUENT(1011, "操作过于频繁，请稍后再试"),

    /** 原密码错误 */
    OLD_PASSWORD_ERROR(1012, "原密码错误"),

    /**
     * 陌生设备：需要二次校验（前端收到后展示验证码，校验通过并勾选"信任此设备"后写入信任）。
     *
     * <p>注意：该错误码不表示账号或密码有误，避免被利用做账号枚举。
     */
    DEVICE_NOT_TRUSTED(1013, "首次在此设备登录，请输入验证码完成验证"),

    /**
     * 需要轻验证：拖动滑块拼合图片即可完成（无需辨认文字或图形）。
     *
     * <p>响应 data 携带一次性票据 {@code ChallengeResp}（含缺口位置），
     * 前端完成拖动后连同票据、落点与轨迹一起提交。
     */
    VERIFY_LIGHT_REQUIRED(1014, "请拖动滑块拼合图片"),

    /**
     * 需要强验证：一次性码等第二因子（风险较高或轻验证不可用时的降级通道）。
     *
     * <p>响应 data 携带一次性票据，前端先请求下发验证码，再连同票据一起提交。
     */
    VERIFY_STRONG_REQUIRED(1015, "当前登录存在风险，请输入一次性验证码完成验证"),

    /**
     * 验证未通过：票据不存在、已过期、上下文不匹配或已被使用（含重放）。
     *
     * <p>统一提示，不区分具体原因 —— 让攻击者无法通过差异化的错误信息试探系统。
     */
    CHALLENGE_INVALID(1016, "验证已失效，请重新登录"),

    /**
     * 账号未绑定可触达联系方式（邮箱/手机）：无法下发一次性验证码。
     *
     * <p>触发后管理员应补全用户联系方式，而不是让系统静默降级（那样攻击者会利用）。
     */
    ONE_TIME_CODE_TARGET_MISSING(1017, "该账号未绑定邮箱或手机，请联系管理员"),

    /**
     * 一次性码发送失败（SMTP/短信网关错误、网络问题、授权码失效等）。
     *
     * <p>不静默吞掉：失败必须让前端看到，避免"看起来发了但实际没发"的最糟情况。
     */
    ONE_TIME_CODE_SEND_FAILED(1018, "验证码下发失败，请稍后重试或联系管理员"),
    ;

    private final int code;

    private final String msg;
}
